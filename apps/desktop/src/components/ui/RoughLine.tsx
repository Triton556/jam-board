import { useEffect, useRef } from "react";
import rough from "roughjs";

const cache = new Map<string, string>();
export function RoughLine({
  color = "var(--line)",
  frame = false,
}: {
  color?: string;
  frame?: boolean;
}) {
  const ref = useRef<HTMLSpanElement>(null);
  useEffect(() => {
    const element = ref.current;
    if (!element) return;
    const draw = () => {
      const width = Math.round(element.clientWidth);
      const height = Math.round(element.clientHeight);
      const key = `${width}:${height}:${color}:${frame}`;
      let svg = cache.get(key);
      if (!svg) {
        const node = document.createElementNS(
          "http://www.w3.org/2000/svg",
          "svg",
        );
        node.setAttribute("width", String(width));
        node.setAttribute("height", String(height));
        const renderer = rough.svg(node);
        const options = {
          roughness: 1.2,
          bowing: 1,
          stroke: color,
          strokeWidth: frame ? 1.5 : 3,
          seed: 13,
          strokeLineDash: frame ? [6, 5] : undefined,
        };
        node.append(
          frame
            ? renderer.rectangle(3, 3, width - 6, height - 6, options)
            : renderer.line(3, 4, width - 3, 4, options),
        );
        svg = node.outerHTML;
        cache.set(key, svg);
      }
      // Only SVG generated by roughjs is inserted; no user content enters this cache.
      element.innerHTML = svg;
    };
    draw();
    const observer = new ResizeObserver(draw);
    observer.observe(element);
    return () => observer.disconnect();
  }, [color, frame]);
  return (
    <span
      ref={ref}
      className={frame ? "rough-frame" : "rough-line"}
      aria-hidden="true"
    />
  );
}

export function RoughArrow() {
  const ref = useRef<HTMLSpanElement>(null);
  useEffect(() => {
    const element = ref.current;
    if (!element) return;
    const key = "onboarding-arrow";
    let svg = cache.get(key);
    if (!svg) {
      const node = document.createElementNS(
        "http://www.w3.org/2000/svg",
        "svg",
      );
      node.setAttribute("viewBox", "0 0 150 65");
      node.setAttribute("width", "150");
      node.setAttribute("height", "65");
      const renderer = rough.svg(node);
      node.append(
        renderer.path("M3 8 Q75 60 144 29 M127 22 L145 29 L131 43", {
          roughness: 1.2,
          bowing: 1,
          stroke: "var(--line)",
          strokeWidth: 1.5,
          seed: 17,
        }),
      );
      svg = node.outerHTML;
      cache.set(key, svg);
    }
    element.innerHTML = svg;
  }, []);
  return <span ref={ref} className="welcome-arrow" aria-hidden="true" />;
}
